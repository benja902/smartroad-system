(async function() {
  'use strict';
  const frame = document.getElementById('prototype');
  await new Promise(resolve => frame.addEventListener('load',resolve,{once:true}));
  const w = frame.contentWindow;
  const d = frame.contentDocument;
  await d.fonts.ready;
  const app = w.UrbesPrototype;
  const results = [];
  const check = (name,condition) => { results.push({name,passed:Boolean(condition)}); };
  const phone = () => d.querySelector('#focused-phone');
  const text = () => phone().textContent;
  const click = selector => { const el = d.querySelector(selector); if (!el) throw Error(`Missing ${selector}`); el.click(); };
  const select = (selector,value) => { const el = d.querySelector(selector); el.value = value; el.dispatchEvent(new w.Event('change',{bubbles:true})); };
  try {
    check('Manrope local cargada',d.fonts.check('500 16px Manrope'));
    check('Vehículo único y disponibilidad separada',text().includes('Toyota Corolla') && text().includes('Dato de disponibilidad') && !text().includes('funcionando correctamente'));
    app.openScreen('login');
    let form = phone().querySelector('form');
    form.requestSubmit();
    check('Formulario vacío conserva login y muestra validación',app.getState().screen === 'login' && form.elements.email.getAttribute('aria-invalid') === 'true');
    form.elements.email.value = 'review@example.invalid';
    form.elements.password.value = 'dato-ficticio';
    click('#focused-phone [data-action="toggle-password"]');
    check('Contraseña con control accesible',form.elements.password.type === 'text' && phone().querySelector('[aria-label="Ocultar contraseña"]').getAttribute('aria-pressed') === 'true');
    form.requestSubmit();
    check('Acceso ficticio inmediato',app.getState().screen === 'home');
    phone().querySelector('.app-scroll').scrollTop = 80;
    click('#focused-phone [data-app-screen="alerts"]');
    click('#focused-phone [data-app-screen="home"]');
    check('Volver a Inicio retiene scroll y no repite entrada',phone().querySelector('.app-scroll').scrollTop === 80 && phone().querySelectorAll('.first-entrance').length === 0);
    app.setScenario('noData');
    check('Ausencia no inventa métricas ni verde',text().includes('Sin datos del SDA') && !text().includes('4,08') && phone().querySelector('.availability.unknown'));
    app.setScenario('previous');
    check('Dato anterior no se afirma actual',text().includes('ayer, 18:20') && text().includes('No confirma la disponibilidad actual'));
    app.openScreen('alerts');
    const fail = d.getElementById('ack-failure'); fail.checked = true; fail.dispatchEvent(new w.Event('change'));
    click('#focused-phone [data-action="ack-moderate"]');
    check('Fallo del acuse conserva atención',phone().querySelector('.attention-card') && text().includes('El aviso sigue pendiente'));
    fail.checked = false; fail.dispatchEvent(new w.Event('change'));
    click('#focused-phone [data-action="ack-moderate"]');
    check('Éxito del acuse personal pasa a historial',!phone().querySelector('.attention-card') && text().includes('Ya lo viste') && text().includes('No se canceló'));
    app.setScenario('deferred');
    check('Grave diferido no abre emergencia',app.getState().screen === 'alerts' && text().includes('Recepción diferida') && !phone().querySelector('[data-critical]'));
    app.setScenario('unknown');
    check('Desconocido permanece técnico',text().includes('Tipo de evento desconocido') && !phone().querySelector('[data-critical]'));
    app.openScreen('home'); app.setScenario('loading');
    click('[data-action="simulate-critical"]');
    check('Emergencia interrumpe carga sin entrada ni barra',app.getState().screen === 'emergency' && phone().querySelector('[data-critical]') && !phone().querySelector('.first-entrance') && !phone().querySelector('.nav-bar'));
    app.setScenario('noLocation');
    check('Ubicación ausente explícita',text().includes('Ubicación no disponible') && !phone().querySelector('.coordinates') && !text().includes('nunca'));
    app.setScenario('lastLocation');
    check('Última posición no es actual',text().includes('No es ubicación actual') && text().includes('420 s'));
    app.setScenario('noTime');
    check('Hora desconocida separada de recepción',text().includes('No disponible') && text().includes('09:41'));
    select('#critical-type','sos');
    check('SOS identifica origen manual',text().includes('Auxilio') && text().includes('Solicitud manual') && !text().includes('Detección automática'));
    fail.checked = true; fail.dispatchEvent(new w.Event('change'));
    click('#focused-phone [data-action="ack-critical"]');
    check('Fallo crítico conserva pantalla',app.getState().screen === 'emergency' && text().includes('La emergencia sigue visible'));
    fail.checked = false; fail.dispatchEvent(new w.Event('change'));
    click('#focused-phone [data-action="ack-critical"]');
    check('Acuse crítico vuelve a Inicio sin cancelar',app.getState().screen === 'home' && app.getState().criticalAck && text().includes('no cancela'));
    app.openScreen('emergency'); app.setScenario('deferred');
    check('Escenario diferido sale inmediatamente de crítica',app.getState().screen === 'alerts');
    const reduce = d.getElementById('reduce-motion'); reduce.checked = true; reduce.dispatchEvent(new w.Event('change'));
    const control = phone().querySelector('.nav-icon');
    check('Movimiento reducido elimina transiciones',w.getComputedStyle(control).transitionDuration === '0s');
    frame.width = '320'; frame.height = '640';
    select('#text-scale','2');
    for (const screen of ['login','home','alerts','emergency']) {
      app.openScreen(screen);
      app.setScenario(screen === 'login' ? 'ready' : screen === 'home' ? 'reported' : screen === 'alerts' ? 'attention' : 'active');
      const container = phone().querySelector('.phone');
      const scroll = container.querySelector('.app-scroll');
      check(`${screen}: 320×640, texto 200 %, sin desborde horizontal`,container.scrollWidth <= container.clientWidth + 1 && scroll.scrollWidth <= scroll.clientWidth + 1);
      const controls = [...container.querySelectorAll('.button:not(:disabled),.eye-button,.nav-item:not([aria-disabled])')];
      check(`${screen}: controles activos de al menos 48 px`,controls.every(el => el.getBoundingClientRect().height >= 48));
    }
    check('Mapa pendiente no es acción habilitada',phone().querySelector('button[disabled]')?.textContent.includes('Ver mapa'));
    check('No hay llamada ni cancelación ficticias',!phone().querySelector('[data-action="call"],[data-action="cancel"]'));
    const ack = phone().querySelector('[data-action="ack-critical"]');
    const scope = d.getElementById(ack.getAttribute('aria-describedby'));
    check('Texto grande conserva el alcance del acuse sin ocupar la mitad del viewport',scope?.textContent.includes('No cancela') && phone().querySelector('.emergency-actions').getBoundingClientRect().height < 200);
  } catch (error) { results.push({name:'Ejecución del harness',passed:false,error:error.message}); }
  const passed = results.every(item => item.passed);
  const report = document.getElementById('report');
  report.dataset.result = passed ? 'passed' : 'failed';
  report.textContent = JSON.stringify({passed,total:results.length,results},null,2);
})();
