// Offline extraction of the approved vehicle only. No runtime JS dependency.
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
const base = new URL('../', import.meta.url);
const context = vm.createContext({});
context.window = context;
const read = name => readFileSync(new URL(`motion_prototype_01/${name}`, base), 'utf8');
vm.runInContext(read('assets.js'), context);
vm.runInContext(read('vehicle.js'), context);
const {parts} = context.URBES_ASSETS, V = context.VehicleMotion;
const manifest = JSON.parse(readFileSync(new URL('composition_v3/manifest.json', base)));
for (const name of ['assets.js', 'vehicle.js']) {
  if (createHash('sha256').update(read(name)).digest('hex') !== manifest.source_hashes[name]) throw Error(`Source changed: ${name}`);
}
const color = s => !s || s === 'none' ? 'null' : `const Color(0xFF${s.slice(1)})`;
const lines = ["// GENERATED by generate_vehicle.mjs. Approved 42-part vehicle, not pose sprites.", "part of 'premium_vehicle.dart';", 'List<_VehiclePart> _buildVehicleParts() => ['];
for (const p of parts) lines.push(`_VehiclePart([${p.points.map(v=>`_Point3(${v.join(',')})`).join(',')}], _Point3(${p.normal.join(',')}), ${color(p.fill)}, ${color(p.stroke)}, ${p.width}, ${p.kind === 'polygon'}),`);
lines.push('];');
writeFileSync(new URL('../../../lib/presentation/premium_scene/premium_vehicle_geometry.g.dart', base), lines.join('\n'));
const samples = [0,600,800,1100,1400,1700,2000,2160,2300,2600].map(ms => {
  const pose = V.at(V.ease((ms-600)/2000)), c=Math.cos(pose.angle), s=Math.sin(pose.angle);
  const faces=parts.map((p,id)=> {
    const points=p.points.map(([x,y,z])=>[pose.x+x*c-y*s,pose.y+x*s+y*c,z]);
    const [nx,ny,nz]=p.normal;
    return {id,visible:nx*c-ny*s+nx*s+ny*c+nz>1e-7,depth:points.reduce((n,p)=>n+p[0]+p[1]+p[2],0)/points.length,first:V.project(points[0])};
  }).sort((a,b)=>a.depth-b.depth||a.id-b.id);
  return {ms,pose,faces};
});
writeFileSync(new URL('flutter_increment_1/vehicle_reference.json', base), JSON.stringify({source_hashes:{'assets.js':manifest.source_hashes['assets.js'],'vehicle.js':manifest.source_hashes['vehicle.js']},route_length:V.routeLength,samples},null,2));
console.log(`Prepared ${parts.length} original vehicle parts and ${samples.length} independent JS reference samples.`);
