"""Offline URBES outlines from the existing OFL Manrope font, weight 800.

Uses fontTools already available in the authoring environment; not a Flutter
dependency. No download, font changes or runtime font loading.
"""
from pathlib import Path
import hashlib,json
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.basePen import BasePen

base=Path(__file__).resolve().parents[1]
repo=base.parents[2]
source=base/'assets/Manrope-variable.ttf'
digest=hashlib.sha256(source.read_bytes()).hexdigest()
assert digest==json.loads((base/'composition_v3/manifest.json').read_text())['source_hashes']['../assets/Manrope-variable.ttf']
font=instantiateVariableFont(TTFont(source),{'wght':800},inplace=False)
glyphs=font.getGlyphSet(); cmap=font.getBestCmap(); scale=32/font['head'].unitsPerEm
names=[cmap[ord(c)] for c in 'URBES']
def kern(left,right):
    value=0
    if 'GPOS' not in font:return value
    gpos=font['GPOS'].table
    indexes={i for f in gpos.FeatureList.FeatureRecord if f.FeatureTag=='kern' for i in f.Feature.LookupListIndex}
    for i in sorted(indexes):
        lookup=gpos.LookupList.Lookup[i]
        assert lookup.LookupType==2,lookup.LookupType
        for table in lookup.SubTable:
            if left not in table.Coverage.glyphs:continue
            if table.Format==1:
                pairs=table.PairSet[table.Coverage.glyphs.index(left)].PairValueRecord
                record=next((p for p in pairs if p.SecondGlyph==right),None)
                adjustment=record.Value1 if record else None
            else:
                assert table.Format==2
                c1=table.ClassDef1.classDefs.get(left,0);c2=table.ClassDef2.classDefs.get(right,0)
                adjustment=table.Class1Record[c1].Class2Record[c2].Value1
            if adjustment:value+=getattr(adjustment,'XAdvance',0)
    return value
commands=[]
def n(x):return f'{x:.6f}'.rstrip('0').rstrip('.') if x else '0'
class Pen(BasePen):
    def __init__(self,x):super().__init__(glyphs);self.x=x
    def point(self,p):return f'{n((self.x+p[0])*scale)}, {n(-p[1]*scale)}'
    def _moveTo(self,p):commands.append(f'..moveTo({self.point(p)})')
    def _lineTo(self,p):commands.append(f'..lineTo({self.point(p)})')
    def _curveToOne(self,a,b,c):commands.append(f'..cubicTo({self.point(a)}, {self.point(b)}, {self.point(c)})')
    def _qCurveToOne(self,a,b):commands.append(f'..quadraticBezierTo({self.point(a)}, {self.point(b)})')
    def _closePath(self):commands.append('..close()')
    def _endPath(self):pass
x=0;adjustments=[]
for i,name in enumerate(names):
    glyphs[name].draw(Pen(x));x+=glyphs[name].width
    if i+1<len(names):
        k=kern(name,names[i+1]);adjustments.append(k);x+=k
text="// GENERATED by generate_wordmark.py from Manrope wght=800.\n// Copyright 2018 The Manrope Project Authors; SIL OFL 1.1.\n// See docs/ui_ux/premium_phase1/assets/OFL.txt and FONTLOG.txt.\npart of 'premium_scene.dart';\nPath _buildUrbesWordmark() => Path()\n  "+'\n  '.join(commands)+';\n'
(repo/'lib/screens/dev/premium_scene/premium_wordmark.g.dart').write_text(text,encoding='utf-8')
(base/'flutter_increment_1/wordmark_manifest.json').write_text(json.dumps({'source':'../assets/Manrope-variable.ttf','sha256':digest,'weight':800,'font_size':32,'glyphs':names,'pair_adjustments_font_units':adjustments,'advance':x*scale,'commands':len(commands),'license':'../assets/OFL.txt'},indent=2),encoding='utf-8')
print(f'Prepared URBES wordmark: {len(commands)} path commands, advance={x*scale}, kerning={adjustments}.')
